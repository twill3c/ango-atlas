"""仮名遣い非依存の折りたたみ表現(F-07)。

**設計判断**: 「旧仮名 → 新仮名」の可読変換ではなく、両者を共通表現へ**対称に**畳む。
理由は F-07 の目的が「文体特徴量が表記ではなく文体を捉えること」の担保であり、
可読変換(語ごとの文脈判断が要る)より、両版に同じ関数を掛ける方が目的に忠実で検証もできる。
原文は `data/raw` に不変で残るので、可読表示は原文を使う(F-12)。

規則は記憶からではなく、**二重版 50 組の差分の実測**から導出した
(`docs/kana_fold_calibration.md`)。効果も同じ 50 組で測る。

規則群と実測効果(2026-08-25、50 組の一致率の中央値):
    素                       0.9488
  + G1 踊り字展開             0.9501
  + G2 小書き→大書き          0.9655
  + G3 ゐゑぢづ               0.9739
  + G5 ハ行転呼・を           (順序が重要 — G4 より先に適用する)
  + G4 長音(au/iu/eu)        0.9964
残差は仮名遣いではなく底本差(咒/呪・言/云・括弧の種別・句読点)で、正規化では詰められない。
"""
from __future__ import annotations

import re

# --- G1: 踊り字 ---------------------------------------------------------
_DAKUTENABLE = "かきくけこさしすせそたちつてとはひふへほカキクケコサシスセソタチツテトハヒフヘホ"


def _dakuten(ch: str) -> str:
    """濁点付きの字へ。濁点を持たない字はそのまま返す。"""
    return chr(ord(ch) + 1) if ch in _DAKUTENABLE else ch


def expand_odoriji(s: str) -> str:
    """踊り字を展開する。ゝゞヽヾ々 と、2 字を繰り返すくの字点 ／＼・／″＼。"""
    s = re.sub(r"(..)／″＼", lambda m: m.group(1) + _dakuten(m.group(1)[0]) + m.group(1)[1], s)
    s = re.sub(r"(..)／＼", lambda m: m.group(1) * 2, s)
    out: list[str] = []
    for ch in s:
        if not out:
            out.append(ch)
        elif ch in "ゝヽ々":
            out.append(out[-1])
        elif ch in "ゞヾ":
            out.append(_dakuten(out[-1]))
        else:
            out.append(ch)
    return "".join(out)


# --- G2: 小書き → 大書き ------------------------------------------------
_SMALL = str.maketrans(
    "っゃゅょぁぃぅぇぉゎッャュョァィゥェォヮ",
    "つやゆよあいうえおわツヤユヨアイウエオワ",
)

# --- G3: 旧仮名の字体 ---------------------------------------------------
_KYUJI = str.maketrans("ゐゑヰヱぢづヂヅ", "いえイエじずジズ")

# --- G5: ハ行転呼・を ---------------------------------------------------
# 助詞の は/へ/を も畳むが、両版に同じ関数を掛けるので比較・特徴量では対称に効く
_HAGYO = str.maketrans("はひふへほハヒフヘホをヲ", "わいうえおワイウエオおオ")

# --- G4: 長音(歴史的仮名遣いの au / iu / eu) ---------------------------
_AU = {
    "あ": "お", "か": "こ", "さ": "そ", "た": "と", "な": "の", "は": "ほ", "ま": "も",
    "や": "よ", "ら": "ろ", "わ": "お", "が": "ご", "ざ": "ぞ", "だ": "ど", "ば": "ぼ",
    "ぱ": "ぽ",
}
_EU = {
    "え": "よ", "け": "きよ", "せ": "しよ", "て": "ちよ", "ね": "によ", "へ": "ひよ",
    "め": "みよ", "れ": "りよ", "げ": "ぎよ", "ぜ": "じよ", "べ": "びよ", "ぺ": "ぴよ",
}
_IYA = "きしちにひみりぎじびぴ"
_AU_RE = re.compile("([" + "".join(_AU) + "])う")
_EU_RE = re.compile("([" + "".join(_EU) + "])う")
_IYA_RE = re.compile("([" + _IYA + "])やう")


def fold_choon(s: str) -> str:
    s = _IYA_RE.sub(lambda m: m.group(1) + "よう", s)
    s = _EU_RE.sub(lambda m: _EU[m.group(1)] + "う", s)
    s = _AU_RE.sub(lambda m: _AU[m.group(1)] + "う", s)
    return s


def fold(s: str) -> str:
    """仮名遣い非依存の表現へ畳む。新仮名・旧仮名の双方に同じものを掛ける。

    適用順が結果を変える。ハ行転呼(G5)を長音(G4)より先に置くこと:
    旧「しまふ」→「しまう」→「しもう」、新「しまう」→「しもう」で一致する。
    逆順だと新側だけが「しもう」になり、かえって差が開く(実測 2026-08-25)。
    """
    s = expand_odoriji(s)
    s = s.translate(_SMALL)
    s = s.translate(_KYUJI)
    s = s.translate(_HAGYO)
    return fold_choon(s)


# --- 可読な現代仮名遣いへの寄せ(埋め込み入力用) -----------------------------
# `fold` と違い、こちらは**読める日本語**を保つ。助詞の は/へ/を は触らない。
# ハ行転呼は「漢字の直後の ひ/ふ/ほ」に限る(思ふ→思う、幸ひ→幸い)。
# 「へ」は助詞と語中の区別がつかないので触らない(東京へ → 東京え を避ける)。
_KANJI_HA = re.compile(r"([一-鿿々])([ひふほ])")
_KANJI_HA_MAP = {"ひ": "い", "ふ": "う", "ほ": "お"}

# 拗音・長音は小書き仮名のある現代表記へ
_YOUON = {
    "きやう": "きょう", "しやう": "しょう", "ちやう": "ちょう", "にやう": "にょう",
    "ひやう": "ひょう", "みやう": "みょう", "りやう": "りょう", "ぎやう": "ぎょう",
    "じやう": "じょう", "びやう": "びょう", "ぴやう": "ぴょう",
    "きゆう": "きゅう", "しゆう": "しゅう", "ちゆう": "ちゅう", "にゆう": "にゅう",
    "ひゆう": "ひゅう", "りゆう": "りゅう", "じゆう": "じゅう",
    "けふ": "きょう", "てふ": "ちょう", "せう": "しょう", "けう": "きょう",
    "てう": "ちょう", "ねう": "にょう", "へう": "ひょう", "めう": "みょう",
    "れう": "りょう", "げう": "ぎょう", "ぜう": "じょう", "べう": "びょう",
    "さう": "そう", "かう": "こう", "たう": "とう", "なう": "のう", "まう": "もう",
    "やう": "よう", "らう": "ろう", "わう": "おう", "がう": "ごう", "ざう": "ぞう",
    "だう": "どう", "ばう": "ぼう", "ぱう": "ぽう",
}
_YOUON_RE = re.compile("|".join(sorted(_YOUON, key=len, reverse=True)))


def to_modern(s: str) -> str:
    """旧仮名を現代仮名遣いへ寄せる(可読性を保つ best-effort)。

    `fold` が比較用の破壊的な畳み込みなのに対し、こちらは埋め込みモデルに与える
    自然な日本語を作るためのもの。完全な変換ではなく、誤変換もありうる —
    効果は二重版チャンク対応(data/eval_variant_chunks.json)で実測して判断する。
    """
    s = expand_odoriji(s)
    s = s.translate(_KYUJI)
    s = _YOUON_RE.sub(lambda m: _YOUON[m.group(0)], s)
    s = _KANJI_HA.sub(lambda m: m.group(1) + _KANJI_HA_MAP[m.group(2)], s)
    # 仮名だけで綴られる高頻度の語尾。実測(旧仮名 60 作品)で いふ 2,290 / まふ 179 と
    # 突出しており、他(にふ・をふ 等)は語頭の「ふ」に当たる危険があるので入れない
    s = s.replace("いふ", "いう").replace("まふ", "まう")
    return s
